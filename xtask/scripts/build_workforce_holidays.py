#!/usr/bin/env python3
"""Builds content/leadership/ma_legal_holidays.yaml (Massachusetts legal holidays 2026-2028).

The dates are computed from the rule in M.G.L. c. 4, s. 7, clause Eighteenth (read on
2026-11-12 at malegislature.gov) with Python's calendar module, independent of the Rust code
that reads the file. The generated list is compared with the Trial Court's published closing
dates for 2026 and 2027 (mass.gov "Trial Court Legal Holidays", last updated 2026-03-20); every
Trial Court date matches (the script asserts it). The Trial Court list has no 2028 and does not
list the Suffolk-county-only days; those dates are computed only.

    python3 xtask/scripts/build_workforce_holidays.py           # write the file
    python3 xtask/scripts/build_workforce_holidays.py --check   # fail if the file is out of date
"""
import calendar
import datetime as dt
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "content" / "leadership" / "ma_legal_holidays.yaml"
YEARS = (2026, 2027, 2028)

# Trial Court "Court Will Be Closed" dates (None = not closed because the holiday is a Saturday).
TRIAL_COURT = {
    2026: {
        "New Year's Day": "2026-01-01", "MLK Day": "2026-01-19",
        "Washington's Birthday": "2026-02-16", "Patriots' Day": "2026-04-20",
        "Memorial Day": "2026-05-25", "Juneteenth": "2026-06-19", "Independence Day": None,
        "Labor Day": "2026-09-07", "Columbus Day": "2026-10-12",
        "Veterans Day": "2026-11-11", "Thanksgiving Day": "2026-11-26",
        "Christmas Day": "2026-12-25",
    },
    2027: {
        "New Year's Day": "2027-01-01", "MLK Day": "2027-01-18",
        "Washington's Birthday": "2027-02-15", "Patriots' Day": "2027-04-19",
        "Memorial Day": "2027-05-31", "Juneteenth": None, "Independence Day": "2027-07-05",
        "Labor Day": "2027-09-06", "Columbus Day": "2027-10-11",
        "Veterans Day": "2027-11-11", "Thanksgiving Day": "2027-11-25",
        "Christmas Day": None,
    },
}


def nth_weekday(year, month, weekday, n):
    """n-th (1-based) given weekday (Mon=0) of a month; n=-1 means the last."""
    days = [d for d in calendar.Calendar().itermonthdates(year, month)
            if d.month == month and d.weekday() == weekday]
    return days[n - 1] if n > 0 else days[-1]


def sunday_rule(d):
    """'or the day following when any of said days occurs on Sunday'."""
    return d + dt.timedelta(days=1) if d.weekday() == 6 else d


def holidays_for(year):
    out = []

    def add(name, d, rule, scope="statewide", moved_from=None):
        out.append({"date": d, "name": name, "rule": rule, "scope": scope, "moved_from": moved_from})

    for name, m, day in [("New Year's Day", 1, 1), ("Juneteenth", 6, 19), ("Independence Day", 7, 4),
                         ("Veterans Day", 11, 11), ("Christmas Day", 12, 25)]:
        d0 = dt.date(year, m, day)
        d = sunday_rule(d0)
        add(name, d, "fixed date; the day following when it falls on a Sunday",
            moved_from=d0 if d != d0 else None)
    add("MLK Day", nth_weekday(year, 1, 0, 3), "third Monday in January")
    add("Washington's Birthday", nth_weekday(year, 2, 0, 3), "third Monday in February")
    add("Patriots' Day", nth_weekday(year, 4, 0, 3), "third Monday in April")
    add("Memorial Day", nth_weekday(year, 5, 0, -1), "last Monday in May")
    add("Labor Day", nth_weekday(year, 9, 0, 1), "first Monday in September")
    add("Columbus Day", nth_weekday(year, 10, 0, 2), "second Monday in October")
    add("Thanksgiving Day", nth_weekday(year, 11, 3, 4),
        "fourth Thursday in November (clause Eighteenth names Thanksgiving Day without a date)")
    for name, m, day in [("Evacuation Day", 3, 17), ("Bunker Hill Day", 6, 17)]:
        d0 = dt.date(year, m, day)
        d = sunday_rule(d0)
        add(name, d, "Suffolk county only; fixed date, the day following when it falls on a Sunday",
            scope="suffolk", moved_from=d0 if d != d0 else None)
    out.sort(key=lambda h: (h["date"], h["name"]))
    return out


def check_against_trial_court():
    for year, table in TRIAL_COURT.items():
        mine = {h["name"]: h["date"] for h in holidays_for(year) if h["scope"] == "statewide"}
        for name, want in table.items():
            d = mine[name]
            # The Trial Court closes only on weekdays; a Saturday holiday is not moved.
            got = d.isoformat() if d.weekday() < 5 else None
            assert got == want, f"{year} {name}: computed {got}, Trial Court list {want}"


def q(s):
    return '"' + s.replace('"', '\\"') + '"'


def render():
    check_against_trial_court()
    L = []
    a = L.append
    a("# Massachusetts legal holidays 2026-2028 for the Open Meeting Law notice calculator")
    a("# (board_of_health_meeting_assistant, LEAD-07).")
    a("#")
    a("# GENERATED by xtask/scripts/build_workforce_holidays.py from M.G.L. c. 4, s. 7, clause Eighteenth;")
    a("# do not edit by hand (run the script with --check in CI). REVIEW STATUS: pending.")
    a("# Schema: content/schemas/leadership_ma_legal_holidays.schema.json")
    a("meta:")
    a("  id: leadership-ma-legal-holidays")
    a("  title: Massachusetts legal holidays 2026-2028 (G.L. c. 4, s. 7, clause Eighteenth)")
    a("  version: 0.1.0")
    a("  prepared: 2026-11-12")
    a("  effective_date: null")
    a("  source:")
    a("    title: M.G.L. c. 4, s. 7 (clause Eighteenth defines legal holiday)")
    a("    publisher: Massachusetts Legislature")
    a("    url: https://malegislature.gov/Laws/GeneralLaws/PartI/TitleI/Chapter4/Section7")
    a("  related_sources:")
    a("    - title: Trial Court Legal Holidays (closing dates for 2026 and 2027, last updated March 20, 2026)")
    a("      publisher: Massachusetts Trial Court")
    a("      url: https://www.mass.gov/info-details/trial-court-legal-holidays")
    a("  review:")
    a("    status: pending")
    a("    reviewed_by: null")
    a("    reviewed_on: null")
    a("    review_due: 2027-02-01")
    a("  verification_note: >-")
    a("    Dates are computed from the statute's rule (read 2026-11-12) and the 2026 and 2027 statewide dates")
    a("    were compared, one by one, with the Trial Court's published closing dates; all agree. 2028 and the")
    a("    two Suffolk-county-only days (Evacuation Day, Bunker Hill Day) have no second published list and")
    a("    are computed only (confidence medium). Thanksgiving is the fourth Thursday of November (the clause")
    a("    names the day but not its date; the Trial Court dates for 2026 and 2027 agree). The statute moves")
    a("    a holiday that falls on a Sunday to the Monday and does not move one that falls on a Saturday;")
    a("    Saturday holidays are listed with their weekday and change nothing for the 48-hour count.")
    a("    The Secretary of the Commonwealth's holiday pages and state personnel pages were blocked.")
    a("")
    a("sources:")
    a("  statute:")
    a("    title: M.G.L. c. 4, s. 7, clause Eighteenth (legal holiday)")
    a("    publisher: Massachusetts Legislature")
    a("    url: https://malegislature.gov/Laws/GeneralLaws/PartI/TitleI/Chapter4/Section7")
    a("    effective_date: null")
    a("    retrieved: 2026-11-12")
    a("  trial_court:")
    a("    title: Trial Court Legal Holidays")
    a("    publisher: Massachusetts Trial Court")
    a("    url: https://www.mass.gov/info-details/trial-court-legal-holidays")
    a('    effective_date: "2026-03-20"')
    a("    retrieved: 2026-11-12")
    a("")
    a("suffolk_county_note: >-")
    a("  Evacuation Day (March 17) and Bunker Hill Day (June 17) are legal holidays with respect to Suffolk")
    a("  county only (Boston, Chelsea, Revere, Winthrop). The statute also says state and municipal offices in")
    a("  Suffolk county stay open on those days. Whether a Suffolk board of health counts them in the")
    a("  48-hour notice period is for its town counsel; the tool excludes them when you say the board is in Suffolk county.")
    a("")
    a("holidays:")
    for y in YEARS:
        for h in holidays_for(y):
            d = h["date"]
            a(f"  - date: {q(d.isoformat())}")
            a(f"    weekday: {calendar.day_name[d.weekday()]}")
            a(f"    name: {q(h['name'])}")
            a(f"    scope: {h['scope']}")
            a(f"    rule: {q(h['rule'])}")
            a(f"    moved_from: {q(h['moved_from'].isoformat()) if h['moved_from'] else 'null'}")
            tc = TRIAL_COURT.get(y, {}).get(h["name"], "absent") if h["scope"] == "statewide" else "absent"
            a(f"    second_source: {'trial_court' if tc != 'absent' else 'none'}")
            a(f"    confidence: {'high' if tc != 'absent' else 'medium'}")
    return "\n".join(L) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date; run build_workforce_holidays.py", file=sys.stderr)
            sys.exit(1)
        print("ma_legal_holidays.yaml is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
