// ------------------------------------------------------------------------ SPC
//
// Reference values: `tests/fixtures/spc.json`, generated by
// `tests/fixtures/generators/spc.R` (qcc 2.7: xbar.one with σ = MR̄/d₂, p, u,
// and c charts; beyond-limit points are 1-based).

mod spc_golden {
    use super::rel;
    use phn_epi::spc::{ChartType, Input, Rule, chart};
    use serde_json::Value;

    fn nums(v: &Value) -> Vec<f64> {
        match v {
            Value::Array(a) => a.iter().map(|x| x.as_f64().unwrap()).collect(),
            other => vec![other.as_f64().unwrap()],
        }
    }

    fn check(fx: &Value, key: &str, input: Input) {
        let c = chart(&input).unwrap();
        let want = &fx[key];
        let center = want["center"].as_f64().unwrap();
        let (lcl, ucl) = (nums(&want["lcl"]), nums(&want["ucl"]));
        for (i, p) in c.points.iter().enumerate() {
            assert!(rel(p.center, center) < 1e-12, "{key} center");
            let l = lcl[i.min(lcl.len() - 1)];
            let u = ucl[i.min(ucl.len() - 1)];
            assert!(
                rel(p.lcl.unwrap(), l.max(0.0)) < 1e-9
                    || (p.lcl.unwrap() - l.max(0.0)).abs() < 1e-12,
                "{key} lcl {i}"
            );
            assert!(
                rel(p.ucl.unwrap(), u) < 1e-9,
                "{key} ucl {i}: {} vs {u}",
                p.ucl.unwrap()
            );
        }
        let beyond: Vec<usize> = nums(&want["beyond"])
            .iter()
            .map(|v| *v as usize - 1)
            .collect();
        let ours: Vec<usize> = c
            .points
            .iter()
            .enumerate()
            .filter(|(_, p)| p.signals.contains(&Rule::OutsideLimits))
            .map(|(i, _)| i)
            .collect();
        assert_eq!(ours, beyond, "{key} points beyond limits");
    }

    #[test]
    fn control_limits_match_qcc() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/spc.json")).unwrap();
        let input = |chart, v: &str, d: Option<&str>| Input {
            chart,
            values: nums(&fx[v]),
            denominators: d.map(|d| nums(&fx[d])),
            phase_starts: vec![],
            baseline: None,
        };
        check(&fx, "xmr", input(ChartType::Xmr, "x", None));
        check(&fx, "p", input(ChartType::P, "num", Some("den")));
        check(&fx, "u", input(ChartType::U, "cnt", Some("expo")));
        check(&fx, "c", input(ChartType::C, "cnt", None));
        // Limits from a 12-point baseline applied to later points.
        let c = chart(&Input {
            baseline: Some(12),
            ..input(ChartType::Xmr, "x", None)
        })
        .unwrap();
        let b = &fx["xmr_baseline12"];
        assert!(rel(c.points[19].center, b["center"].as_f64().unwrap()) < 1e-12);
        assert!(rel(c.points[19].lcl.unwrap(), b["lcl"].as_f64().unwrap()) < 1e-9);
        assert!(rel(c.points[19].ucl.unwrap(), b["ucl"].as_f64().unwrap()) < 1e-9);
    }
}
