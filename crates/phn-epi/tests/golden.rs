//! Golden tests: exact Poisson intervals against SciPy reference values
//! (`tests/fixtures/poisson_exact_ci.json`, generated with
//! `scipy.stats.chi2.ppf`, SciPy 1.18).

use phn_epi::rates::{poisson_exact_ci, rate};

#[derive(serde::Deserialize)]
struct Case {
    count: u64,
    confidence: f64,
    lower: f64,
    upper: f64,
}

#[derive(serde::Deserialize)]
struct Fixture {
    cases: Vec<Case>,
}

fn rel(a: f64, b: f64) -> f64 {
    if b == 0.0 {
        a.abs()
    } else {
        ((a - b) / b).abs()
    }
}

#[test]
fn exact_poisson_intervals_match_scipy() {
    let f: Fixture = serde_json::from_str(include_str!("fixtures/poisson_exact_ci.json")).unwrap();
    assert!(f.cases.len() >= 60);
    for c in &f.cases {
        let (lo, hi) = poisson_exact_ci(c.count, c.confidence);
        assert!(
            rel(lo, c.lower) < 1e-7 && rel(hi, c.upper) < 1e-7,
            "count {} at {}: got ({lo}, {hi}), expected ({}, {})",
            c.count,
            c.confidence,
            c.lower,
            c.upper
        );
    }
}

#[test]
fn rate_interval_is_count_interval_scaled() {
    // 25 cases in a town of 40,000, per 100,000.
    let r = rate("Town", 25, 40_000.0, 100_000.0, 0.95, 5);
    let (lo, hi) = poisson_exact_ci(25, 0.95);
    assert!((r.rate - 62.5).abs() < 1e-12);
    assert!(rel(r.lower, lo * 2.5) < 1e-12);
    assert!(rel(r.upper, hi * 2.5) < 1e-12);
}

// ------------------------------------------------------------------ 2×2 tables
//
// Reference values: `tests/fixtures/two_by_two.json`, generated by
// `tests/fixtures/generators/two_by_two.R` (R fisher.test, chisq.test,
// mantelhaen.test, and epitools oddsratio/riskratio) and
// `two_by_two_statsmodels.py` (statsmodels StratifiedTable: Breslow–Day with
// Tarone's correction and the Mantel–Haenszel risk ratio).

mod two_by_two_golden {
    use super::rel;
    use phn_epi::two_by_two::{Design, Table, analyze, mantel_haenszel};
    use serde_json::Value;

    fn f(v: &Value, k: &str) -> Option<f64> {
        v.get(k).and_then(Value::as_f64)
    }

    fn close(got: f64, want: f64, tol: f64, what: &str, case: &Value) {
        assert!(
            rel(got, want) < tol || (got - want).abs() < 1e-12,
            "{what}: got {got}, expected {want} for {case}"
        );
    }

    #[test]
    fn single_tables_match_r() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/two_by_two.json")).unwrap();
        let tables = fx["tables"].as_array().unwrap();
        assert!(tables.len() >= 10);
        for c in tables {
            let t = Table::new(
                c["a"].as_u64().unwrap(),
                c["b"].as_u64().unwrap(),
                c["c"].as_u64().unwrap(),
                c["d"].as_u64().unwrap(),
            );
            let r = analyze(t, Design::Cohort, 0.95);
            let p = |name: &str| {
                r.exact
                    .iter()
                    .chain(r.chi_square.iter())
                    .find(|x| x.name.starts_with(name))
                    .unwrap_or_else(|| panic!("{name} missing for {c}"))
                    .clone()
            };
            close(
                p("Fisher exact, two-sided").p_value,
                f(c, "fisher_two_sided").unwrap(),
                1e-6,
                "Fisher two-sided",
                c,
            );
            close(
                p("Fisher exact, one-sided (exposure increases").p_value,
                f(c, "fisher_greater").unwrap(),
                1e-6,
                "Fisher greater",
                c,
            );
            close(
                p("Fisher exact, one-sided (exposure decreases").p_value,
                f(c, "fisher_less").unwrap(),
                1e-6,
                "Fisher less",
                c,
            );
            // Conditional MLE and Fisher interval: tight against SciPy (brentq),
            // loose against R, whose uniroot tolerance is about 1e-4.
            let ex = r.odds_ratio_exact.as_ref().unwrap();
            // (R's uniroot solves for ψ or 1/ψ on (0, 1) with an absolute
            // tolerance of about 1.2e-4, so its check also accepts an absolute
            // difference below 2e-4 on either scale.)
            for (key, tol) in [("scipy_or_", 1e-7), ("or_", 2e-3)] {
                let close = |got: f64, want: f64, tol: f64, what: &str, case: &Value| {
                    if key == "or_"
                        && ((got - want).abs() < 2e-4 || (1.0 / got - 1.0 / want).abs() < 2e-4)
                    {
                        return;
                    }
                    close(got, want, tol, what, case)
                };
                let mle = f(c, &format!("{key}mle")).unwrap_or(f64::INFINITY);
                if mle.is_finite() && mle > 0.0 {
                    close(ex.value, mle, tol, "conditional MLE OR", c);
                }
                close(
                    ex.lower,
                    f(c, &format!("{key}exact_lower")).unwrap(),
                    tol,
                    "exact OR lower",
                    c,
                );
                match f(c, &format!("{key}exact_upper")) {
                    Some(u) => close(ex.upper.unwrap(), u, tol, "exact OR upper", c),
                    None => assert!(ex.upper.is_none(), "upper should be infinite for {c}"),
                }
            }
            if let Some(w) = f(c, "or_woolf") {
                let o = r.odds_ratio.as_ref().unwrap();
                close(o.value, w, 1e-9, "Woolf OR", c);
                close(
                    o.lower,
                    f(c, "or_woolf_lower").unwrap(),
                    1e-7,
                    "Woolf lower",
                    c,
                );
                close(
                    o.upper.unwrap(),
                    f(c, "or_woolf_upper").unwrap(),
                    1e-7,
                    "Woolf upper",
                    c,
                );
            }
            if let Some(rr) = f(c, "rr") {
                let e = r.risk_ratio.as_ref().unwrap();
                close(e.value, rr, 1e-9, "RR", c);
                close(e.lower, f(c, "rr_lower").unwrap(), 1e-7, "RR lower", c);
                close(
                    e.upper.unwrap(),
                    f(c, "rr_upper").unwrap(),
                    1e-7,
                    "RR upper",
                    c,
                );
            }
            // Mid-p interval: tight against SciPy, loose against epitools (uniroot).
            let m = r.odds_ratio_mid_p.as_ref().unwrap();
            close(
                m.lower,
                f(c, "scipy_midp_lower").unwrap(),
                1e-7,
                "mid-p lower",
                c,
            );
            match f(c, "scipy_midp_upper") {
                Some(u) => close(m.upper.unwrap(), u, 1e-7, "mid-p upper", c),
                None => assert!(m.upper.is_none(), "mid-p upper should be infinite for {c}"),
            }
            if let Some(lo) = f(c, "or_midp_lower") {
                let up = f(c, "or_midp_upper").unwrap();
                let ok = |got: f64, want: f64| {
                    rel(got, want) < 2e-3
                        || (got - want).abs() < 2e-4
                        || (1.0 / got - 1.0 / want).abs() < 2e-4
                };
                assert!(
                    ok(m.lower, lo) && ok(m.upper.unwrap(), up),
                    "mid-p vs epitools for {c}"
                );
            }
            if let Some(x2) = f(c, "chisq") {
                close(
                    p("Pearson").statistic.unwrap(),
                    x2,
                    1e-9,
                    "Pearson chi-square",
                    c,
                );
                close(
                    p("Yates").statistic.unwrap(),
                    f(c, "chisq_yates").unwrap(),
                    1e-9,
                    "Yates chi-square",
                    c,
                );
                close(
                    p("Yates").p_value,
                    f(c, "chisq_yates_p").unwrap(),
                    1e-7,
                    "Yates p",
                    c,
                );
            }
        }
    }

    #[test]
    fn stratified_analysis_matches_r_and_statsmodels() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/two_by_two.json")).unwrap();
        for s in fx["stratified"].as_array().unwrap() {
            let strata: Vec<Table> = s["strata"]
                .as_array()
                .unwrap()
                .iter()
                .map(|t| {
                    let v: Vec<u64> = t
                        .as_array()
                        .unwrap()
                        .iter()
                        .map(|x| x.as_u64().unwrap())
                        .collect();
                    Table::new(v[0], v[1], v[2], v[3])
                })
                .collect();
            let r = mantel_haenszel(&strata, Design::Cohort, 0.95);
            let or = r.mh_odds_ratio.as_ref().unwrap();
            close(or.value, f(s, "mh_or").unwrap(), 1e-9, "MH OR", s);
            close(
                or.lower,
                f(s, "mh_or_lower").unwrap(),
                1e-7,
                "MH OR lower",
                s,
            );
            close(
                or.upper.unwrap(),
                f(s, "mh_or_upper").unwrap(),
                1e-7,
                "MH OR upper",
                s,
            );
            let t = r.mh_test.as_ref().unwrap();
            close(
                t.statistic.unwrap(),
                f(s, "mh_stat").unwrap(),
                1e-9,
                "MH statistic",
                s,
            );
            close(t.p_value, f(s, "mh_p").unwrap(), 1e-7, "MH p", s);
            let bd = r.breslow_day.as_ref().unwrap();
            close(
                bd.statistic.unwrap(),
                f(s, "breslow_day_tarone_stat").unwrap(),
                1e-6,
                "Breslow-Day",
                s,
            );
            close(
                bd.p_value,
                f(s, "breslow_day_tarone_p").unwrap(),
                1e-6,
                "Breslow-Day p",
                s,
            );
            close(
                r.mh_risk_ratio.as_ref().unwrap().value,
                f(s, "mh_rr").unwrap(),
                1e-9,
                "MH RR",
                s,
            );
        }
    }
}

// ------------------------------------------------------------ standardization
//
// Reference values: `tests/fixtures/standardize.json`, generated by
// `tests/fixtures/generators/standardize.R` (epitools::ageadjust.direct for
// the Fay–Feuer gamma interval; stats::poisson.test for SIR/SMR).

mod standardize_golden {
    use super::rel;
    use phn_epi::standardize::{Stratum, direct_adjust, indirect};
    use serde_json::Value;

    fn nums(v: &Value) -> Vec<f64> {
        v.as_array()
            .unwrap()
            .iter()
            .map(|x| x.as_f64().unwrap())
            .collect()
    }

    #[test]
    fn direct_adjustment_matches_epitools() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/standardize.json")).unwrap();
        for c in fx["direct"].as_array().unwrap() {
            let (count, pop, std) = (nums(&c["count"]), nums(&c["pop"]), nums(&c["standard"]));
            let strata: Vec<Stratum> = (0..count.len())
                .map(|i| Stratum {
                    count: count[i] as u64,
                    population: pop[i],
                    standard: std[i],
                })
                .collect();
            for (conf, lo_k, hi_k) in [(0.95, "lower", "upper"), (0.90, "lower90", "upper90")] {
                let r = direct_adjust(&strata, 1.0, conf);
                // R returns "NaN" for the lower limit with zero events; ours is 0.
                let want = |k: &str| c[k].as_f64().unwrap_or(0.0);
                assert!(rel(r.crude_rate, want("crude")) < 1e-12, "crude {c}");
                assert!(rel(r.rate, want("adjusted")) < 1e-12, "adjusted {c}");
                assert!(
                    rel(r.lower, want(lo_k)) < 1e-9 || (r.lower - want(lo_k)).abs() < 1e-15,
                    "lower {conf} {c}"
                );
                assert!(
                    rel(r.upper, want(hi_k)) < 1e-9,
                    "upper {conf}: {} vs {} {c}",
                    r.upper,
                    want(hi_k)
                );
            }
        }
    }

    #[test]
    fn indirect_standardization_matches_poisson_test() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/standardize.json")).unwrap();
        for c in fx["indirect"].as_array().unwrap() {
            let o = c["observed"].as_u64().unwrap();
            let e = c["expected"].as_f64().unwrap();
            let want = |k: &str| c[k].as_f64().unwrap();
            let r = indirect(o, e, 0.95);
            assert!(rel(r.ratio, want("ratio")) < 1e-12, "{c}");
            assert!(
                rel(r.lower, want("lower")) < 1e-8 || r.lower == 0.0 && want("lower") == 0.0,
                "lower {c}"
            );
            assert!(rel(r.upper, want("upper")) < 1e-8, "upper {c}");
            assert!(
                rel(r.p_value, want("p")) < 1e-8,
                "p: {} vs {} {c}",
                r.p_value,
                want("p")
            );
            let r90 = indirect(o, e, 0.90);
            assert!(rel(r90.upper, want("upper90")) < 1e-8, "upper90 {c}");
        }
    }
}

// ----------------------------------------------------------------------- GLMs
//
// Reference values: `tests/fixtures/glm.json`, generated by
// `tests/fixtures/generators/glm.R` (R glm and MASS::glm.nb, epsilon 1e-12).

mod glm_golden {
    use super::rel;
    use phn_epi::glm::{Family, GlmData, fit};
    use serde_json::Value;

    fn nums(v: &Value) -> Vec<f64> {
        v.as_array()
            .unwrap()
            .iter()
            .map(|x| x.as_f64().unwrap())
            .collect()
    }

    #[test]
    fn fits_match_r() {
        let fx: Value = serde_json::from_str(include_str!("fixtures/glm.json")).unwrap();
        for c in fx["cases"].as_array().unwrap() {
            let family = match c["family"].as_str().unwrap() {
                "poisson" => Family::Poisson,
                "negative_binomial" => Family::NegativeBinomial,
                "binomial" => Family::Binomial,
                _ => Family::Gaussian,
            };
            let x: Vec<Vec<f64>> = c["design"].as_array().unwrap().iter().map(nums).collect();
            let names: Vec<String> = c["names"]
                .as_array()
                .unwrap()
                .iter()
                .map(|v| v.as_str().unwrap().to_string())
                .collect();
            let data = GlmData {
                y: nums(&c["y"]),
                x,
                names,
                offset: c.get("offset").filter(|v| v.is_array()).map(nums),
                trials: c.get("trials").filter(|v| v.is_array()).map(nums),
            };
            let f = fit(&data, family, 0.95).unwrap();
            assert!(f.converged, "{family:?}");
            // R takes standard errors from its last IRLS weights; ours use the
            // converged estimates, so values agree to about 1e-7.
            let tol = if family == Family::NegativeBinomial {
                1e-5
            } else {
                1e-6
            };
            for (k, (key, got)) in [
                (
                    "coef",
                    f.coefficients
                        .iter()
                        .map(|c| c.estimate)
                        .collect::<Vec<_>>(),
                ),
                ("se", f.coefficients.iter().map(|c| c.std_error).collect()),
                ("stat", f.coefficients.iter().map(|c| c.statistic).collect()),
                ("p", f.coefficients.iter().map(|c| c.p_value).collect()),
            ]
            .into_iter()
            .enumerate()
            {
                let want = nums(&c[key]);
                for (g, w) in got.iter().zip(&want) {
                    let t = if k == 3 { tol * 100.0 } else { tol };
                    assert!(
                        rel(*g, *w) < t || (g - w).abs() < 1e-12,
                        "{family:?} {key}: {g} vs {w}"
                    );
                }
            }
            for (key, got) in [
                ("deviance", f.deviance),
                ("null_deviance", f.null_deviance),
                ("aic", f.aic),
                ("loglik", f.log_likelihood),
                ("df_residual", f.df_residual),
            ] {
                let w = c[key].as_f64().unwrap();
                assert!(rel(got, w) < tol, "{family:?} {key}: {got} vs {w}");
            }
            if let Some(th) = c.get("theta").and_then(Value::as_f64) {
                assert!(
                    rel(f.theta.unwrap(), th) < 1e-5,
                    "theta {} vs {th}",
                    f.theta.unwrap()
                );
                let se = c["theta_se"].as_f64().unwrap();
                assert!(rel(f.theta_std_error.unwrap(), se) < 1e-4, "theta se");
            }
        }
    }
}

